namespace BuildTool.Build;

/// <summary>
/// Generates and compiles a minimal Windows launcher stub executable.
/// The launcher uses CreateProcess() to launch the actual game binary
/// via a relative path, matching the UE shipped directory structure.
///
/// Output layout reference (UE shipped):
///   Root/{ProjectName}.exe                                          (~250KB launcher stub)
///   Root/{ProjectName}/Binaries/Win64/{ProjectName}-Win64-Shipping.exe  (monolithic game)
///
/// The launcher resolves its own directory at runtime and constructs
/// a relative path to the game executable. Pure Win32 API - no dev tools required.
/// </summary>
public static class LauncherStubBuilder
{
    /// <summary>Result of launcher stub compilation.</summary>
    public sealed class LauncherBuildResult
    {
        /// <summary>Whether the build succeeded.</summary>
        public required bool Success { get; init; }

        /// <summary>Absolute path to the compiled launcher EXE (on success).</summary>
        public string? ExePath { get; init; }

        /// <summary>Error message (on failure).</summary>
        public string? Error { get; init; }

        public static LauncherBuildResult Ok(string exePath) =>
            new() { Success = true, ExePath = exePath };

        public static LauncherBuildResult Fail(string error) =>
            new() { Success = false, Error = error };
    }

    /// <summary>
    /// Build the launcher stub executable via CMake.
    /// </summary>
    /// <param name="projectName">Game project name (e.g. "EnigmaArcade").</param>
    /// <param name="platform">Target platform (e.g. "Win64").</param>
    /// <param name="intermediateDir">
    /// Root intermediate directory. Sources go to {intermediateDir}/Source/,
    /// build output to {intermediateDir}/Build/.
    /// </param>
    /// <param name="cmake">CMakeInvoker instance for configure/build.</param>
    /// <returns>LauncherBuildResult with path to compiled EXE on success.</returns>
    public static LauncherBuildResult Build(
        string projectName, string platform,
        string intermediateDir, CMakeInvoker cmake)
    {
        try
        {
            string sourceDir = Path.Combine(intermediateDir, "Source");
            string buildDir = Path.Combine(intermediateDir, "Build");
            Directory.CreateDirectory(sourceDir);
            Directory.CreateDirectory(buildDir);

            // 1. Write LauncherStub.cpp
            string cppContent = GenerateCppSource(projectName, platform);
            string cppPath = Path.Combine(sourceDir, "LauncherStub.cpp");
            File.WriteAllText(cppPath, cppContent);

            // 2. Write CMakeLists.txt
            string cmakeContent = GenerateCMakeLists(projectName);
            string cmakePath = Path.Combine(sourceDir, "CMakeLists.txt");
            File.WriteAllText(cmakePath, cmakeContent);

            // 3. CMake configure
            Console.WriteLine("[LauncherStub] Configuring ...");
            var configResult = cmake.Configure(
                sourceDir, buildDir, "Visual Studio 17 2022");
            if (!configResult.Success)
                return LauncherBuildResult.Fail(
                    $"CMake configure failed: {configResult.Output}");

            // 4. CMake build (Release for minimal size)
            Console.WriteLine("[LauncherStub] Building ...");
            var buildResult = cmake.Build(buildDir, "Release");
            if (!buildResult.Success)
                return LauncherBuildResult.Fail(
                    $"CMake build failed: {buildResult.Output}");

            // 5. Locate compiled executable
            string? exePath = FindCompiledExe(buildDir, "LauncherStub.exe");
            if (exePath is null)
                return LauncherBuildResult.Fail(
                    "Launcher stub compiled but executable not found in build output.");

            Console.WriteLine($"[LauncherStub] Built: {exePath}");
            return LauncherBuildResult.Ok(exePath);
        }
        catch (Exception ex)
        {
            return LauncherBuildResult.Fail($"Launcher stub build error: {ex.Message}");
        }
    }

    /// <summary>
    /// Generate the LauncherStub.cpp source content.
    /// Uses pure Win32 API: GetModuleFileNameA → relative path → CreateProcessA.
    /// </summary>
    internal static string GenerateCppSource(string projectName, string platform)
    {
        return $$"""
            // Auto-generated by EnigmaEngine BuildTool - do not edit.
            // Minimal launcher stub: resolves own directory, launches game executable via relative path.

            #ifndef WIN32_LEAN_AND_MEAN
            #define WIN32_LEAN_AND_MEAN
            #endif
            #include <windows.h>
            #include <stdio.h>

            int main(int argc, char* argv[])
            {
                // 1. Get the directory containing this launcher executable
                char launcherPath[MAX_PATH];
                DWORD len = GetModuleFileNameA(NULL, launcherPath, MAX_PATH);
                if (len == 0 || len >= MAX_PATH)
                {
                    MessageBoxA(NULL,
                        "Failed to determine launcher directory.",
                        "{{projectName}} Launcher", MB_OK | MB_ICONERROR);
                    return 1;
                }

                // Strip filename to get directory
                char* lastSlash = launcherPath;
                for (char* p = launcherPath; *p; ++p)
                {
                    if (*p == '\\' || *p == '/')
                        lastSlash = p;
                }
                *lastSlash = '\0';

                // 2. Construct relative path to game executable
                char targetPath[MAX_PATH];
                int written = _snprintf_s(targetPath, MAX_PATH, _TRUNCATE,
                    "%s\\{{projectName}}\\Binaries\\{{platform}}\\{{projectName}}-{{platform}}-Shipping.exe",
                    launcherPath);

                if (written < 0)
                {
                    MessageBoxA(NULL,
                        "Path to game executable is too long.",
                        "{{projectName}} Launcher", MB_OK | MB_ICONERROR);
                    return 1;
                }

                // 3. Build command line: pass through all arguments
                char cmdLine[32768] = {0};
                _snprintf_s(cmdLine, sizeof(cmdLine), _TRUNCATE, "\"%s\"", targetPath);
                for (int i = 1; i < argc; ++i)
                {
                    size_t cmdLen = strlen(cmdLine);
                    _snprintf_s(cmdLine + cmdLen, sizeof(cmdLine) - cmdLen, _TRUNCATE,
                        " \"%s\"", argv[i]);
                }

                // 4. Launch the game process
                STARTUPINFOA si = {0};
                si.cb = sizeof(si);
                PROCESS_INFORMATION pi = {0};

                BOOL ok = CreateProcessA(
                    targetPath,     // lpApplicationName
                    cmdLine,        // lpCommandLine
                    NULL, NULL,     // security attributes
                    FALSE,          // inherit handles
                    0,              // creation flags
                    NULL,           // environment (inherit)
                    launcherPath,   // working directory = launcher's directory
                    &si, &pi);

                if (!ok)
                {
                    char errMsg[1024];
                    _snprintf_s(errMsg, sizeof(errMsg), _TRUNCATE,
                        "Failed to launch game executable.\n\n"
                        "Expected path:\n%s\n\n"
                        "Error code: %lu",
                        targetPath, GetLastError());
                    MessageBoxA(NULL, errMsg,
                        "{{projectName}} Launcher", MB_OK | MB_ICONERROR);
                    return 1;
                }

                // 5. Wait for game to exit and forward its exit code
                WaitForSingleObject(pi.hProcess, INFINITE);

                DWORD exitCode = 0;
                GetExitCodeProcess(pi.hProcess, &exitCode);

                CloseHandle(pi.hProcess);
                CloseHandle(pi.hThread);

                return (int)exitCode;
            }
            """;
    }

    /// <summary>
    /// Generate a minimal CMakeLists.txt for compiling the launcher stub.
    /// </summary>
    internal static string GenerateCMakeLists(string projectName)
    {
        return $"""
            cmake_minimum_required(VERSION 3.20)
            project({projectName}Launcher CXX)
            add_executable(LauncherStub LauncherStub.cpp)
            if(MSVC)
                target_compile_options(LauncherStub PRIVATE /W3)
                target_link_options(LauncherStub PRIVATE /SUBSYSTEM:CONSOLE)
            endif()
            """;
    }

    /// <summary>
    /// Recursively search for the compiled executable in the build directory.
    /// Multi-config generators (Visual Studio) place output in config subdirectories.
    /// </summary>
    private static string? FindCompiledExe(string buildDir, string exeName)
    {
        var files = Directory.GetFiles(buildDir, exeName, SearchOption.AllDirectories);
        return files.Length > 0 ? files[0] : null;
    }
}